/**
 * Expo config plugin: background chapter preparation (brief N4).
 *
 * The app keeps preparing chapters while it is in the background, through react-native-background-
 * actions' foreground service. This plugin makes the Android manifest allow it:
 *  - FOREGROUND_SERVICE, FOREGROUND_SERVICE_DATA_SYNC: run the service, of the dataSync type.
 *  - POST_NOTIFICATIONS: show the progress notification on Android 13 and later. The app asks for it
 *    at runtime; without it the service still runs and only the notification is hidden.
 *  - The library's service gets android:foregroundServiceType="dataSync". Android 14 and later throw
 *    MissingForegroundServiceTypeException for a foreground service without a type.
 *  - A monochrome notification icon, written into res/drawable. The library resolves it by name.
 *
 * android/ is generated by `expo prebuild`, so nothing is edited there by hand. Every step is
 * idempotent, so re-running prebuild leaves the same manifest.
 */
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const PERMISSIONS = [
  'android.permission.FOREGROUND_SERVICE',
  'android.permission.FOREGROUND_SERVICE_DATA_SYNC',
  'android.permission.POST_NOTIFICATIONS',
];
const LIBRARY_SERVICE = 'com.asterinet.react.bgactions.RNBackgroundActionsTask';
const ICON_NAME = 'ic_stat_lectio';
const TOOLS_NAMESPACE = 'http://schemas.android.com/tools';

/**
 * A white book on a transparent background, in a 24 dp box. Android tints a status-bar icon, so only
 * its alpha shape matters.
 */
const ICON_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Lectio notification icon (brief N4). Monochrome: Android tints it. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="M2,5.5 Q6.5,3.5 11,5.5 L11,19 Q6.5,17.5 2,19 Z M13,5.5 Q17.5,3.5 22,5.5 L22,19 Q17.5,17.5 13,19 Z" />
</vector>
`;

/** Adds the permissions the manifest does not declare yet. */
function addPermissions(manifest) {
  const declared = manifest['uses-permission'] ?? [];
  for (const name of PERMISSIONS) {
    if (!declared.some((entry) => entry.$?.['android:name'] === name)) {
      declared.push({ $: { 'android:name': name } });
    }
  }
  manifest['uses-permission'] = declared;
}

/** Declares the dataSync type on the library's service, adding the entry when it is not there. */
function declareServiceType(application) {
  const services = application.service ?? [];
  let service = services.find((entry) => entry.$?.['android:name'] === LIBRARY_SERVICE);
  if (!service) {
    service = { $: { 'android:name': LIBRARY_SERVICE } };
    services.push(service);
  }
  service.$['android:foregroundServiceType'] = 'dataSync';
  application.service = services;
}

/**
 * Rewrites the parsed AndroidManifest (the xml2js shape `{ manifest: {...} }`) and returns it. Throws
 * when the manifest has no application element, which means it is not an Android app manifest.
 */
function patchManifest(modResults) {
  const { manifest } = modResults;
  const application = manifest.application?.[0];
  if (!application)
    throw new Error('with-background-processing: the manifest has no <application>.');
  manifest.$ = manifest.$ ?? {};
  manifest.$['xmlns:tools'] ??= TOOLS_NAMESPACE;
  addPermissions(manifest);
  declareServiceType(application);
  return modResults;
}

/** Writes the notification icon into the app's drawable folder. */
function writeNotificationIcon(platformRoot) {
  const drawable = path.join(platformRoot, 'app', 'src', 'main', 'res', 'drawable');
  fs.mkdirSync(drawable, { recursive: true });
  fs.writeFileSync(path.join(drawable, `${ICON_NAME}.xml`), ICON_XML);
}

function withBackgroundProcessing(config) {
  const withIcon = withDangerousMod(config, [
    'android',
    async (cfg) => {
      writeNotificationIcon(cfg.modRequest.platformProjectRoot);
      return cfg;
    },
  ]);
  return withAndroidManifest(withIcon, (cfg) => {
    cfg.modResults = patchManifest(cfg.modResults);
    return cfg;
  });
}

module.exports = withBackgroundProcessing;
module.exports.patchManifest = patchManifest;
module.exports.writeNotificationIcon = writeNotificationIcon;
module.exports.ICON_XML = ICON_XML;
module.exports.ICON_NAME = ICON_NAME;
module.exports.PERMISSIONS = PERMISSIONS;
module.exports.LIBRARY_SERVICE = LIBRARY_SERVICE;
